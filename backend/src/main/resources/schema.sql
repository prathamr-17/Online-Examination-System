CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL, role VARCHAR(12) NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash VARCHAR(64) PRIMARY KEY, user_id BIGINT NOT NULL,
  expires_at BIGINT NOT NULL, revoked BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS exams (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL, title VARCHAR(120) NOT NULL, subject VARCHAR(80) NOT NULL,
  description VARCHAR(2000) NOT NULL, type VARCHAR(20) NOT NULL, minutes INT NOT NULL,
  starts_at BIGINT NOT NULL, ends_at BIGINT NOT NULL, color VARCHAR(20) NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, exam_id BIGINT NOT NULL,
  prompt VARCHAR(2000) NOT NULL, type VARCHAR(20) NOT NULL, options_json CLOB NOT NULL,
  correct_answer VARCHAR(500), marks INT NOT NULL, position INT NOT NULL
);
CREATE TABLE IF NOT EXISTS attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, exam_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL, started_at BIGINT NOT NULL, deadline BIGINT NOT NULL,
  submitted_at BIGINT, status VARCHAR(20) NOT NULL, warnings INT NOT NULL DEFAULT 0,
  UNIQUE(exam_id, student_id)
);
CREATE TABLE IF NOT EXISTS answers (
  attempt_id BIGINT NOT NULL, question_id BIGINT NOT NULL, answer CLOB NOT NULL,
  awarded INT, PRIMARY KEY(attempt_id, question_id)
);
CREATE TABLE IF NOT EXISTS integrity_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, attempt_id BIGINT NOT NULL,
  type VARCHAR(32) NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS grades (
  attempt_id BIGINT NOT NULL, question_id BIGINT NOT NULL, awarded INT NOT NULL,
  PRIMARY KEY(attempt_id, question_id)
);
CREATE INDEX IF NOT EXISTS idx_exams_schedule ON exams(starts_at, ends_at);
CREATE INDEX IF NOT EXISTS idx_attempts_student ON attempts(student_id, submitted_at);
